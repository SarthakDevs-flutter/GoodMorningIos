import 'morning_devotional_content.dart';

/// Dedicated offline prayer-only cycle.
///
/// This is intentionally separate from [MorningDevotionalContent] so the
/// "Prayer only" mission is not just the Scripture plan with the verse hidden.
class PrayerOnlyContent {
  PrayerOnlyContent._();

  static const cycleLength = 365;
  static final DateTime _cycleStart = DateTime(2026, 1, 5);

  static MorningDevotionalItem forDate([
    DateTime? date,
    String languageCode = 'ko',
  ]) {
    final raw = date ?? DateTime.now();
    final day = DateTime(raw.year, raw.month, raw.day);
    final offset = day.difference(_cycleStart).inDays;
    final index = _positiveMod(offset, cycleLength);
    final code = MorningDevotionalLocalization.normalize(languageCode);
    final topic = _topics[index % _topics.length];
    final movement = _movements[(index ~/ _topics.length) % _movements.length];

    return MorningDevotionalItem(
      themeName: _planTitle(code),
      weekdayLabel: _dayLabel(code, index + 1),
      verse: '',
      reference: '',
      prayer: _composePrayer(code, topic, movement),
      translation: '',
      languageCode: code,
    );
  }

  static int _positiveMod(int value, int divisor) {
    return ((value % divisor) + divisor) % divisor;
  }

  static String _planTitle(String code) {
    return switch (code) {
      'ko' => '기도 전용 365',
      'de' => '365 Gebete',
      'ru' => '365 молитв',
      'es' => '365 oraciones',
      'pt' => '365 Orações',
      'zh' => '365祷告',
      'ja' => '365の祈り',
      _ => '365 Prayer',
    };
  }

  static String _dayLabel(String code, int day) {
    return switch (code) {
      'ko' => '$day일차 기도',
      'de' => 'Gebet Tag $day',
      'ru' => 'Молитва, день $day',
      'es' => 'Oración día $day',
      'pt' => 'Oração dia $day',
      'zh' => '第$day天祷告',
      'ja' => '祈り $day日目',
      _ => 'Prayer Day $day',
    };
  }

  static String _composePrayer(
    String code,
    _PrayerTopic topic,
    _PrayerMovement movement,
  ) {
    return switch (code) {
      'ko' => '주님, 오늘 제게 필요한 은혜는 ${topic.ko}입니다. ${movement.ko} 아멘.',
      'de' =>
        'Herr, die Gnade, die ich heute brauche, ist: ${topic.de}. ${movement.de} Amen.',
      'ru' =>
        'Господи, сегодня мне нужна благодать: ${topic.ru}. ${movement.ru} Аминь.',
      'es' =>
        'Señor, la gracia que necesito hoy es ${topic.es}. ${movement.es} Amén.',
      'pt' =>
        'Senhor, a graça de que preciso hoje é ${topic.pt}. ${movement.pt} Amém.',
      'zh' => '主啊，我今天需要的恩典是${topic.zh}。${movement.zh}阿们。',
      'ja' => '主よ、今日わたしに必要な恵みは${topic.ja}です。${movement.ja} アーメン。',
      _ => 'Lord, the grace I need today is ${topic.en}. ${movement.en} Amen.',
    };
  }

